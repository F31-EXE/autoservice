def expand(pattern: str) -> tuple[str, str]:
    """Return (kind, pattern) with placeholders expanded."""
    if pattern.startswith("re:"):
        return "regex", pattern[3:]
    return "keywords", pattern.replace("{R}", R).replace("{REPAIR}", REPAIR)


def load(apps=None) -> int:
    """Upsert global catalog. Usable from migrations (``apps``) and the seed command."""
    if apps is None:
        from django.apps import apps as global_apps

        apps = global_apps
    WorkType = apps.get_model("catalog", "WorkType")
    WorkTypeAlias = apps.get_model("catalog", "WorkTypeAlias")
    for code, name, category, km, months, urgency, regular, aliases in WORK_TYPES:
        wt, _ = WorkType.objects.update_or_create(
            code=code,
            defaults={
                "name": name,
                "category": category,
                "default_interval_km": km,
                "default_interval_months": months,
                "urgency_default": urgency,
                "is_regular": regular,
            },
        )
        WorkTypeAlias.objects.filter(work_type=wt, station__isnull=True).delete()
        WorkTypeAlias.objects.bulk_create(
            [WorkTypeAlias(work_type=wt, kind=k, pattern=p) for k, p in map(expand, aliases)]
        )
    return len(WORK_TYPES)
